%% ---------------------------------------------------
%% Function: Create thrust loading table
function [TW_table, T_Wto_takeoff] = createThrustLoadingTable(constraints, aero, thrust, Wto_S_range, constraintNames, TO)
num_constraints = length(constraintNames);
TW_table = zeros(num_constraints, length(Wto_S_range));

for i = 1:num_constraints
name = constraintNames{i};
%NEED A FUNCTION TO COMPUTE WING LOADING
TW_table(i, :) = computeWingLoading(constraints.(name), aero.(name), thrust.(name), Wto_S_range);
end

T_Wto_takeoff = takeoff_constraint(Wto_S_range, TO);
end

%% ---------------------------------------------------
%% Function: Plot constraint diagram
function plotConstraintDiagram(Wto_S_range, TW_table, T_Wto_takeoff, Wto_S_landing, optimal_WS, min_TW, constraintNames)
figure('Name', 'Constraint Diagram'); hold on;
colors = lines(length(constraintNames));

for i = 1:length(constraintNames)
plot(Wto_S_range, TW_table(i, :), 'LineWidth', 2, 'DisplayName', constraintNames{i}, 'Color', colors(i,:));
end

plot(Wto_S_range, T_Wto_takeoff, 'k-', 'LineWidth', 2, 'DisplayName', 'Takeoff');
xline(Wto_S_landing, '--k', 'LineWidth', 2, 'DisplayName', 'Landing');
plot(optimal_WS, min_TW, 'ko', 'MarkerSize', 10, 'MarkerFaceColor', 'g', 'DisplayName', sprintf('Optimum (W/S=%.1f, T/W=%.2f)', optimal_WS, min_TW));
xlabel('Wing Loading W/S [psf]');
ylabel('Thrust-to-Weight Ratio T/W');
title('Constraint Diagram with Optimal Design Point');
legend('Location', 'northeastoutside');
grid on;
end

%% ---------------------------------------------------
%% Function: Show results table as a GUI element
function showResultTable(TW_table, constraintNames, Wto_S_range)
    fig = figure('Name', 'T/W Table');
    uitable(fig, ...
        'Data', round(TW_table, 3), ...
        'ColumnName', compose('W/S = %d', Wto_S_range), ...
        'RowName', constraintNames, ...
        'Units', 'normalized', ...
        'Position', [0 0 1 1]);
end

%% ---------------------------------------------------
%% Function: Solve for optimal W/S and T/W
function [optimal_WS, min_TW] = solveOptimalPoint(TW_table, T_Wto_takeoff, Wto_S_range)
T_Wto_required = max([TW_table; T_Wto_takeoff], [], 1);
[min_TW, min_idx] = min(T_Wto_required);
optimal_WS = Wto_S_range(min_idx);
end

%% ---------------------------------------------------
%% Takeoff Constraint
function T_Wto = takeoff_constraint(Wto_S, TO)
g = 32.174;
V_Vstall = TO.Takeoff.V_Vstall;
beta = TO.Takeoff.W_Wto;
alpha = TO.Takeoff.AB_thrustlapse;
rho = TO.Takeoff.air_density;
CLmax = TO.Takeoff.CLmax;
Distance = TO.Takeoff.Distance;
CD0 = TO.Takeoff.CD0;
mu = TO.Takeoff.mu;
term1 = V_Vstall^2 * beta^2 .* Wto_S ./ (alpha * rho * CLmax * g * Distance);
term2 = 0.7 * CD0 / (beta * CLmax) + mu;
T_Wto = term1 + term2;
end


